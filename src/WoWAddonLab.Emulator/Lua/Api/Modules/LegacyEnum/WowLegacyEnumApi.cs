    public override void Register(lua_State state)
    {
        for (var index = 0; index < FrameTutorials.Length; index++)
        {
            lua_pushinteger(state, index + 1);
            lua_setglobal(state, FrameTutorials[index]);
        }

        lua_pushinteger(state, FrameTutorials.Length);
        lua_setglobal(state, "NUM_LE_FRAME_TUTORIALS");

        SetIntegerGlobal(state, "LE_MOUNT_JOURNAL_FILTER_COLLECTED", 1);
        SetIntegerGlobal(state, "LE_MOUNT_JOURNAL_FILTER_NOT_COLLECTED", 2);
        SetIntegerGlobal(state, "LE_MOUNT_JOURNAL_FILTER_UNUSABLE", 3);
    }

    private static void SetIntegerGlobal(lua_State state, string name, int value)
    {
        lua_pushinteger(state, value);
        lua_setglobal(state, name);
    }
